#include "UndoModel.h"

namespace models {

UndoModel::UndoModel() : _maxHistorySize(100) {
}

UndoModel::~UndoModel() {
    clearHistory();
}

void UndoModel::addActionRecord(const ActionRecord& record) {
    // ??????????
    _undoStack.push(record);
    
    // ????????
    while (!_redoStack.empty()) {
        _redoStack.pop();
    }
    
    // ??????????????
    if (_undoStack.size() > _maxHistorySize) {
        // ??????????????????????????????
        std::stack<ActionRecord> tempStack;
        size_t stackSize = _undoStack.size();
        
        // ?????????_maxHistorySize?????
        for (size_t i = 0; i < stackSize; ++i) {
            ActionRecord action = _undoStack.top();
            _undoStack.pop();
            
            if (i < _maxHistorySize) {
                tempStack.push(action);
            }
        }
        
        // ???????????????????
        while (!tempStack.empty()) {
            _undoStack.push(tempStack.top());
            tempStack.pop();
        }
    }
}

ActionRecord* UndoModel::undo() {
    if (_undoStack.empty()) {
        return nullptr;
    }
    
    // ???????????????????
    ActionRecord record = _undoStack.top();
    _undoStack.pop();
    
    // ??????????
    _redoStack.push(record);
    
    // ???????????????????????????????????????????????????????????????????
    return new ActionRecord(record);
}

ActionRecord* UndoModel::redo() {
    if (_redoStack.empty()) {
        return nullptr;
    }
    
    // ???????????????????
    ActionRecord record = _redoStack.top();
    _redoStack.pop();
    
    // ??????????
    _undoStack.push(record);
    
    // ??????????
    return new ActionRecord(record);
}

void UndoModel::clearHistory() {
    // ???????
    while (!_undoStack.empty()) {
        _undoStack.pop();
    }
    
    // ????????
    while (!_redoStack.empty()) {
        _redoStack.pop();
    }
}

} // namespace models
